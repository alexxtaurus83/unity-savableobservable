using System;
using System.Collections;
using System.Collections.Generic;
using System.Reflection;
using NUnit.Framework;
using TMPro;
using UnityEngine;
using UnityEngine.UI;

namespace SavableObservable.Tests.Contracts {
    /// <summary>
    /// Explicitly skips a Presenter, Model, or AutoBind field during MmvcLiveUiAudit.
    /// </summary>
    [AttributeUsage(AttributeTargets.Class | AttributeTargets.Field | AttributeTargets.Property, Inherited = true, AllowMultiple = false)]
    public class LiveUiAuditSkipAttribute : Attribute {
        public string Reason { get; }

        public LiveUiAuditSkipAttribute(string reason = null) {
            Reason = string.IsNullOrEmpty(reason) ? "Explicitly marked with [LiveUiAuditSkip]" : reason;
        }
    }

    /// <summary>
    /// Execution status for an audited field or unit.
    /// </summary>
    public enum AuditStatus {
        Audited,
        Skipped,
        Failed
    }

    /// <summary>
    /// Result record for an individual [AutoBind] field audited during MmvcLiveUiAudit.
    /// </summary>
    public class AuditedFieldResult {
        public string PresenterTypeName { get; set; }
        public string ModelTypeName { get; set; }
        public string FieldName { get; set; }
        public string TargetVariableName { get; set; }
        public string ControlTypeName { get; set; }
        public AuditStatus Status { get; set; }
        public string Reason { get; set; }
        public Exception Error { get; set; }

        public override string ToString() {
            string prefix = $"[{Status}] {PresenterTypeName}.{FieldName} -> {ModelTypeName}.{TargetVariableName} ({ControlTypeName})";
            return string.IsNullOrEmpty(Reason) ? prefix : $"{prefix}: {Reason}";
        }
    }

    /// <summary>
    /// Configuration options for running MmvcLiveUiAudit.
    /// </summary>
    public class LiveUiAuditOptions {
        public HashSet<string> SkipPresenterTypes { get; } = new HashSet<string>(StringComparer.Ordinal);
        public HashSet<string> SkipModelTypes { get; } = new HashSet<string>(StringComparer.Ordinal);
        public HashSet<string> SkipFields { get; } = new HashSet<string>(StringComparer.Ordinal);
        public bool UsePrefsSandbox { get; set; } = true;
        public Dictionary<string, object> CustomSampleValues { get; } = new Dictionary<string, object>(StringComparer.Ordinal);
        public Dictionary<Type, object> CustomTypeSamples { get; } = new Dictionary<Type, object>();
    }

    /// <summary>
    /// Aggregate report generated by MmvcLiveUiAudit.
    /// </summary>
    public class LiveUiAuditReport {
        public List<AuditedFieldResult> Results { get; } = new List<AuditedFieldResult>();

        public int AuditedCount {
            get {
                int c = 0;
                for (int i = 0; i < Results.Count; i++) if (Results[i].Status == AuditStatus.Audited) c++;
                return c;
            }
        }

        public int SkippedCount {
            get {
                int c = 0;
                for (int i = 0; i < Results.Count; i++) if (Results[i].Status == AuditStatus.Skipped) c++;
                return c;
            }
        }

        public int FailedCount {
            get {
                int c = 0;
                for (int i = 0; i < Results.Count; i++) if (Results[i].Status == AuditStatus.Failed) c++;
                return c;
            }
        }

        public int TotalCount => Results.Count;

        public string SummaryText() {
            var sb = new System.Text.StringBuilder();
            sb.AppendLine($"Live UI Audit Summary: Total={TotalCount}, Audited={AuditedCount}, Skipped={SkippedCount}, Failed={FailedCount}");
            foreach (var r in Results) {
                sb.AppendLine("  " + r.ToString());
            }
            return sb.ToString();
        }
    }

    /// <summary>
    /// Automated live scene / prefab auditor for MMVC units.
    /// Enumerates [AutoBind] fields, drives sample values in both directions,
    /// verifies convergence without bounce-back, and restores original values.
    /// </summary>
    public static class MmvcLiveUiAudit {
        #region Pure Logic & Sample Generation (Testable in EditMode)

        public static bool ShouldSkipPresenter(Type presenterType, LiveUiAuditOptions options, out string reason) {
            if (presenterType == null) {
                reason = "Presenter type is null.";
                return true;
            }
            if (options != null && options.SkipPresenterTypes.Contains(presenterType.Name)) {
                reason = $"Presenter '{presenterType.Name}' is in SkipPresenterTypes.";
                return true;
            }
            var attr = presenterType.GetCustomAttribute<LiveUiAuditSkipAttribute>(true);
            if (attr != null) {
                reason = attr.Reason;
                return true;
            }
            reason = null;
            return false;
        }

        public static bool ShouldSkipModel(Type modelType, LiveUiAuditOptions options, out string reason) {
            if (modelType == null) {
                reason = "Model type is null.";
                return true;
            }
            if (options != null && options.SkipModelTypes.Contains(modelType.Name)) {
                reason = $"Model '{modelType.Name}' is in SkipModelTypes.";
                return true;
            }
            var attr = modelType.GetCustomAttribute<LiveUiAuditSkipAttribute>(true);
            if (attr != null) {
                reason = attr.Reason;
                return true;
            }
            reason = null;
            return false;
        }

        public static bool ShouldSkipField(FieldInfo field, Type presenterType, Type modelType, LiveUiAuditOptions options, out string reason) {
            if (field == null) {
                reason = "Field is null.";
                return true;
            }
            var attr = field.GetCustomAttribute<LiveUiAuditSkipAttribute>(true);
            if (attr != null) {
                reason = attr.Reason;
                return true;
            }
            if (options != null) {
                if (options.SkipFields.Contains(field.Name)) {
                    reason = $"Field '{field.Name}' is in SkipFields.";
                    return true;
                }
                if (presenterType != null && options.SkipFields.Contains($"{presenterType.Name}.{field.Name}")) {
                    reason = $"Field '{presenterType.Name}.{field.Name}' is in SkipFields.";
                    return true;
                }
                var autoBindAttr = field.GetCustomAttribute<AutoBindAttribute>(true);
                string targetVar = autoBindAttr?.VariableName ?? field.Name;
                if (modelType != null && options.SkipFields.Contains($"{modelType.Name}.{targetVar}")) {
                    reason = $"Model variable '{modelType.Name}.{targetVar}' is in SkipFields.";
                    return true;
                }
            }
            reason = null;
            return false;
        }

        public static object GenerateSampleValue(Type targetType, object currentValue, Component uiControl = null, int variant = 1) {
            if (targetType == typeof(bool)) {
                bool b = currentValue is bool val && val;
                return !b;
            }
            if (targetType == typeof(int)) {
                int current = currentValue is int i ? i : 0;
                if (uiControl is Slider slider) {
                    int min = Mathf.RoundToInt(slider.minValue);
                    int max = Mathf.RoundToInt(slider.maxValue);
                    if (min < max) {
                        int candidate = current + variant;
                        if (candidate > max || candidate < min) candidate = current - variant;
                        if (candidate < min) candidate = min;
                        if (candidate > max) candidate = max;
                        if (candidate == current && min < max) candidate = (current == min) ? min + 1 : min;
                        return candidate;
                    }
                }
                return current + variant;
            }
            if (targetType == typeof(float)) {
                float current = currentValue is float f ? f : 0f;
                if (uiControl is Slider slider) {
                    float min = slider.minValue;
                    float max = slider.maxValue;
                    if (min < max) {
                        float step = (max - min) * 0.25f * variant;
                        float candidate = current + step;
                        if (candidate > max || candidate < min) candidate = current - step;
                        if (candidate < min) candidate = min;
                        if (candidate > max) candidate = max;
                        if (Mathf.Approximately(candidate, current) && min < max) {
                            candidate = Mathf.Approximately(current, min) ? min + (max - min) * 0.5f : min;
                        }
                        return candidate;
                    }
                }
                return current + (1.5f * variant);
            }
            if (targetType == typeof(string)) {
                return $"audit_sample_{variant}";
            }
            if (targetType.IsEnum) {
                var values = Enum.GetValues(targetType);
                if (values.Length > 0) {
                    for (int j = 0; j < values.Length; j++) {
                        if (Equals(values.GetValue(j), currentValue)) {
                            return values.GetValue((j + variant) % values.Length);
                        }
                    }
                    return values.GetValue(variant % values.Length);
                }
            }
            return null;
        }

        private static FieldInfo FindFieldAcrossHierarchy(Type type, string fieldName) {
            for (var curr = type; curr != null && curr != typeof(MonoBehaviour) && curr != typeof(Component) && curr != typeof(UnityEngine.Object) && curr != typeof(object); curr = curr.BaseType) {
                var field = curr.GetField(fieldName, BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly);
                if (field != null) return field;
            }
            return null;
        }

        #endregion

        #region Live Audit Runner

        /// <summary>
        /// Audits all presenters found in the specified root or active scene.
        /// </summary>
        public static IEnumerator RunAudit(
            GameObject root,
            LiveUiAuditReport report,
            LiveUiAuditOptions options = null)
        {
            if (report == null) throw new ArgumentNullException(nameof(report));
            options = options ?? new LiveUiAuditOptions();

            var presenters = new List<MonoBehaviour>();
            if (root != null) {
                foreach (var mb in root.GetComponentsInChildren<MonoBehaviour>(true)) {
                    if (mb is IObservablePresenter) presenters.Add(mb);
                }
            } else {
                foreach (var mb in UnityEngine.Object.FindObjectsByType<MonoBehaviour>(FindObjectsInactive.Include, FindObjectsSortMode.None)) {
                    if (mb is IObservablePresenter) presenters.Add(mb);
                }
            }

            yield return RunAudit(presenters, report, options);
        }

        /// <summary>
        /// Audits an explicit collection of MMVC presenters.
        /// </summary>
        public static IEnumerator RunAudit(
            IEnumerable<MonoBehaviour> presenters,
            LiveUiAuditReport report,
            LiveUiAuditOptions options = null)
        {
            if (report == null) throw new ArgumentNullException(nameof(report));
            options = options ?? new LiveUiAuditOptions();

            PrefsSandboxUtility sandbox = null;
            if (options.UsePrefsSandbox) {
                sandbox = new PrefsSandboxUtility();
                sandbox.Begin();
            }

            try {
                if (presenters != null) {
                    foreach (var presenter in presenters) {
                        if (presenter == null) continue;
                        yield return AuditPresenter(presenter, report, options);
                    }
                }
            } finally {
                if (sandbox != null) {
                    sandbox.Dispose();
                }
            }
        }

        private static IEnumerator AuditPresenter(
            MonoBehaviour presenter,
            LiveUiAuditReport report,
            LiveUiAuditOptions options)
        {
            Type pType = presenter.GetType();
            if (ShouldSkipPresenter(pType, options, out string pSkipReason)) {
                report.Results.Add(new AuditedFieldResult {
                    PresenterTypeName = pType.Name,
                    Status = AuditStatus.Skipped,
                    Reason = pSkipReason
                });
                yield break;
            }

            IObservablePresenter obsPresenter = presenter as IObservablePresenter;
            BaseObservableDataModel model = obsPresenter != null ? obsPresenter.GetObservableModel() : null;

            if (model == null) {
                // Try to find Model on the same GameObject
                model = presenter.GetComponent<BaseObservableDataModel>();
            }

            if (model == null) {
                report.Results.Add(new AuditedFieldResult {
                    PresenterTypeName = pType.Name,
                    Status = AuditStatus.Skipped,
                    Reason = "Presenter has no associated BaseObservableDataModel."
                });
                yield break;
            }

            Type mType = model.GetType();
            if (ShouldSkipModel(mType, options, out string mSkipReason)) {
                report.Results.Add(new AuditedFieldResult {
                    PresenterTypeName = pType.Name,
                    ModelTypeName = mType.Name,
                    Status = AuditStatus.Skipped,
                    Reason = mSkipReason
                });
                yield break;
            }

            // Collect all [AutoBind] fields traversing hierarchy
            var autoBindFields = new List<FieldInfo>();
            for (var curr = pType; curr != null && curr != typeof(MonoBehaviour) && curr != typeof(Component) && curr != typeof(object); curr = curr.BaseType) {
                var fields = curr.GetFields(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly);
                foreach (var f in fields) {
                    if (f.IsDefined(typeof(AutoBindAttribute), true)) {
                        autoBindFields.Add(f);
                    }
                }
            }

            if (autoBindFields.Count == 0) {
                yield break;
            }

            foreach (var f in autoBindFields) {
                yield return AuditField(presenter, model, f, report, options);
            }
        }

        private static IEnumerator AuditField(
            MonoBehaviour presenter,
            BaseObservableDataModel model,
            FieldInfo field,
            LiveUiAuditReport report,
            LiveUiAuditOptions options)
        {
            Type pType = presenter.GetType();
            Type mType = model.GetType();

            var autoBindAttr = field.GetCustomAttribute<AutoBindAttribute>(true);
            string targetVarName = autoBindAttr?.VariableName ?? field.Name;

            var result = new AuditedFieldResult {
                PresenterTypeName = pType.Name,
                ModelTypeName = mType.Name,
                FieldName = field.Name,
                TargetVariableName = targetVarName
            };

            if (ShouldSkipField(field, pType, mType, options, out string fieldSkipReason)) {
                result.Status = AuditStatus.Skipped;
                result.Reason = fieldSkipReason;
                report.Results.Add(result);
                yield break;
            }

            object uiControlObj = field.GetValue(presenter);
            Component uiComp = uiControlObj as Component;
            result.ControlTypeName = uiComp != null ? uiComp.GetType().Name : (uiControlObj != null ? uiControlObj.GetType().Name : "null");

            if (uiComp == null) {
                result.Status = AuditStatus.Failed;
                result.Reason = $"UI control field '{field.Name}' on '{pType.Name}' is null or not a Component.";
                report.Results.Add(result);
                yield break;
            }

            FieldInfo modelField = FindFieldAcrossHierarchy(mType, targetVarName);
            if (modelField == null) {
                result.Status = AuditStatus.Failed;
                result.Reason = $"Model '{mType.Name}' does not have observable field '{targetVarName}'.";
                report.Results.Add(result);
                yield break;
            }

            object observableObj = modelField.GetValue(model);
            if (observableObj == null) {
                result.Status = AuditStatus.Failed;
                result.Reason = $"Observable field '{targetVarName}' on model '{mType.Name}' is null.";
                report.Results.Add(result);
                yield break;
            }

            PropertyInfo valueProp = observableObj.GetType().GetProperty("Value", BindingFlags.Public | BindingFlags.Instance);
            if (valueProp == null) {
                result.Status = AuditStatus.Skipped;
                result.Reason = $"Observable field '{targetVarName}' does not expose a public Value property (e.g. collection).";
                report.Results.Add(result);
                yield break;
            }

            Type valueType = valueProp.PropertyType;
            object originalVal = valueProp.GetValue(observableObj);

            object sample1 = null;
            if (options.CustomSampleValues.TryGetValue($"{mType.Name}.{targetVarName}", out object customVal) ||
                options.CustomSampleValues.TryGetValue(targetVarName, out customVal) ||
                options.CustomTypeSamples.TryGetValue(valueType, out customVal)) {
                sample1 = customVal;
            } else {
                sample1 = GenerateSampleValue(valueType, originalVal, uiComp, 1);
            }

            if (sample1 == null) {
                result.Status = AuditStatus.Skipped;
                result.Reason = $"Cannot generate sample value for type '{valueType.Name}'.";
                report.Results.Add(result);
                yield break;
            }

            try {
                // Step 1: ModelToView
                valueProp.SetValue(observableObj, sample1);
                yield return null;

                // Step 2: ViewToModel (if two-way interactive control)
                Selectable selectable = uiComp as Selectable;
                bool isInteractive = selectable == null || (selectable.enabled && selectable.gameObject.activeInHierarchy && selectable.interactable);

                if (isInteractive) {
                    if (uiComp is Slider slider && (valueType == typeof(float) || valueType == typeof(int))) {
                        object sample2 = GenerateSampleValue(valueType, sample1, uiComp, 2);
                        yield return MmvcLiveUiAssert.SetSlider(slider, Convert.ToSingle(sample2));
                        object afterUiVal = valueProp.GetValue(observableObj);
                        if (valueType == typeof(int)) {
                            Assert.AreEqual(Convert.ToInt32(sample2), Convert.ToInt32(afterUiVal), "Slider ViewToModel convergence");
                        } else {
                            Assert.AreEqual(Convert.ToSingle(sample2), Convert.ToSingle(afterUiVal), 0.001f, "Slider ViewToModel convergence");
                        }
                    } else if (uiComp is Toggle toggle && valueType == typeof(bool)) {
                        bool sample2 = !(bool)sample1;
                        yield return MmvcLiveUiAssert.SetToggle(toggle, sample2);
                        object afterUiVal = valueProp.GetValue(observableObj);
                        Assert.AreEqual(sample2, (bool)afterUiVal, "Toggle ViewToModel convergence");
                    } else if (uiComp is TMP_InputField tmpInput && valueType == typeof(string)) {
                        string sample2 = "audit_type_2";
                        yield return MmvcLiveUiAssert.Type(tmpInput, sample2);
                        object afterUiVal = valueProp.GetValue(observableObj);
                        Assert.AreEqual(sample2, afterUiVal, "TMP_InputField ViewToModel convergence");
                    } else if (uiComp is InputField input && valueType == typeof(string)) {
                        string sample2 = "audit_type_legacy";
                        yield return MmvcLiveUiAssert.Type(input, sample2);
                        object afterUiVal = valueProp.GetValue(observableObj);
                        Assert.AreEqual(sample2, afterUiVal, "InputField ViewToModel convergence");
                    }
                }

                result.Status = AuditStatus.Audited;
                result.Reason = "Successfully audited ModelToView and ViewToModel round-trip.";
                report.Results.Add(result);
            } finally {
                // Restore original value
                try {
                    valueProp.SetValue(observableObj, originalVal);
                } catch {
                    // Ignore restore errors during test cleanup
                }
            }
            yield return null;
        }

        #endregion
    }
